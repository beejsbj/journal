"""`hermes journal setup` / `uninstall`: the cron stub and the no-agent tick job.

Hermes runs cron scripts only from ``$HERMES_HOME/scripts/``, so setup writes a small stub there
that imports this plugin's ``journal`` package and runs one tick. The job itself is created through
the documented ``hermes cron`` CLI (never by editing Hermes' job store): every five minutes, no
agent, output kept locally, failure notices to ``hermes.failure_deliver`` (default: the journal's
Telegram chat). Setup is idempotent: run it again after an update or a move and it only fixes what
differs. Uninstall removes the job and the stub and leaves the journal, state and settings alone.
"""
from __future__ import annotations

import json
import os
import re
import subprocess
import tempfile
from dataclasses import dataclass
from pathlib import Path
from typing import Callable

from ..config import Config

STUB_NAME = "journal-tick.py"
JOB_NAME = "journal tick"

Runner = Callable[[list[str]], subprocess.CompletedProcess]


@dataclass
class Job:
    id: str
    name: str = ""
    script: str = ""
    enabled: bool = True
    schedule: str = ""
    deliver: str = ""
    failure_deliver: str | None = None
    no_agent: bool | None = None
    last_status: str | None = None
    last_run_at: str | None = None


def stub_text(src: Path, home: Path) -> str:
    return f'''"""journal tick — generated by `hermes journal setup`. Do not edit; rerun setup instead."""
import os
import sys

SRC = {str(src)!r}
os.environ["HERMES_HOME"] = {str(home)!r}
if SRC not in sys.path:
    sys.path.insert(0, SRC)

from journal.cli import main  # noqa: E402

raise SystemExit(main(["tick"]))
'''


def stub_path(home: Path) -> Path:
    return Path(home) / "scripts" / STUB_NAME


def write_stub(home: Path, src: Path) -> tuple[Path, bool]:
    path = stub_path(home)
    text = stub_text(src, home)
    if path.is_file() and path.read_text(encoding="utf-8") == text:
        return path, False
    path.parent.mkdir(parents=True, exist_ok=True)
    fd, tmp = tempfile.mkstemp(dir=path.parent, prefix=f".{path.name}.")
    with os.fdopen(fd, "w", encoding="utf-8") as fh:
        fh.write(text)
    os.chmod(tmp, 0o644)
    os.replace(tmp, path)
    return path, True


def failure_target(cfg: Config) -> str:
    fd = cfg.hermes.get("failure_deliver")
    if fd:
        return str(fd)
    return f"{cfg.platform}:{cfg.chat_id}" if cfg.chat_id else "local"  # (Hermes' delivery grammar, any platform)


def hermes_runner(cfg: Config) -> Runner:
    """Run ``hermes <args>`` against exactly the profile home the plugin runs in (``HERMES_HOME``)."""
    env = dict(os.environ)
    if cfg.hermes_home is not None:
        env["HERMES_HOME"] = str(cfg.hermes_home)

    def run(args: list[str]) -> subprocess.CompletedProcess:
        return subprocess.run([cfg.hermes_command(), *args], capture_output=True, text=True, timeout=120, env=env)
    return run


def _jobs_from_store(home: Path) -> list[Job] | None:
    """Read (never write) Hermes' job store when it is present; None when it isn't readable."""
    path = Path(home) / "cron" / "jobs.json"
    try:
        data = json.loads(path.read_text(encoding="utf-8"))
    except (OSError, json.JSONDecodeError):
        return None
    rows = data.get("jobs", []) if isinstance(data, dict) else data
    jobs = []
    for j in rows if isinstance(rows, list) else []:
        if not isinstance(j, dict) or not j.get("id"):
            continue
        sched = j.get("schedule") or {}
        jobs.append(Job(
            id=str(j["id"]), name=str(j.get("name") or ""), script=str(j.get("script") or ""),
            enabled=bool(j.get("enabled", True)) and j.get("state") != "paused",
            schedule=str(sched.get("expr") or sched.get("display") or "") if isinstance(sched, dict) else str(sched),
            deliver=str(j.get("deliver") or ""), failure_deliver=j.get("failure_deliver"),
            no_agent=j.get("no_agent"), last_status=j.get("last_status"), last_run_at=j.get("last_run_at"),
        ))
    return jobs


_BLOCK = re.compile(r"^\s{2}([0-9a-f]{6,})\s*(?:\[(\w+)\])?\s*$")
_FIELD = re.compile(r"^\s{4}(\w[\w ]*?):\s+(.*)$")


def parse_cron_list(text: str) -> list[Job]:
    """Jobs from ``hermes cron list --all`` (fallback when the store isn't readable)."""
    jobs: list[Job] = []
    for line in text.splitlines():
        m = _BLOCK.match(line)
        if m:
            jobs.append(Job(id=m.group(1), enabled=(m.group(2) or "active") not in ("paused", "disabled")))
            continue
        f = _FIELD.match(line)
        if f and jobs:
            key, value = f.group(1).lower(), f.group(2).strip()
            if key == "name":
                jobs[-1].name = value
            elif key == "schedule":
                jobs[-1].schedule = value
            elif key == "deliver":
                jobs[-1].deliver = value
            elif key == "script":
                jobs[-1].script = value
    return jobs


def find_jobs(cfg: Config, run: Runner | None = None) -> list[Job]:
    home = cfg.hermes_home
    jobs = _jobs_from_store(home) if home is not None else None
    if jobs is None:
        out = (run or hermes_runner(cfg))(["cron", "list", "--all"])
        jobs = parse_cron_list(out.stdout or "")
    return [j for j in jobs if Path(j.script).name == STUB_NAME or (not j.script and j.name == JOB_NAME)]


def setup(cfg: Config, src: Path, run: Runner | None = None, paused: bool = False) -> tuple[int, list[str]]:
    """Write the stub and make sure exactly one tick job exists with the expected settings."""
    if cfg.hermes_home is None:
        return 2, ["not running under Hermes (no HERMES_HOME); nothing to set up"]
    run = run or hermes_runner(cfg)
    lines = []
    path, changed = write_stub(cfg.hermes_home, src)
    lines.append(f"{'wrote' if changed else 'kept'} {path}")
    schedule = str(cfg.hermes.get("cron_schedule") or "*/5 * * * *")
    failure = failure_target(cfg)
    jobs = find_jobs(cfg, run)
    if not jobs:
        args = ["cron", "create", schedule, "--no-agent", "--script", STUB_NAME, "--deliver", "local",
                "--failure-deliver", failure, "--name", JOB_NAME]
        if paused:
            args += ["--paused", "--paused-reason", "created paused by hermes journal setup"]
        out = run(args)
        if out.returncode != 0:
            return 1, lines + [f"could not create the cron job: {(out.stderr or out.stdout).strip()[-300:]}"]
        made = find_jobs(cfg, run)
        lines.append(f"created cron job {made[0].id if made else '(id not found yet)'}: {schedule}, "
                     f"no agent, deliver local, failures to {failure}" + (" (paused)" if paused else ""))
        return 0, lines
    job = jobs[0]
    if len(jobs) > 1:
        lines.append(f"warning: {len(jobs)} journal tick jobs exist ({', '.join(j.id for j in jobs)}); "
                     f"keeping {job.id}; remove the others with `hermes cron remove <id>`")
    edits = []
    if job.schedule and job.schedule != schedule:
        edits += ["--schedule", schedule]
    if job.deliver and job.deliver != "local":
        edits += ["--deliver", "local"]
    if job.failure_deliver is not None and job.failure_deliver != failure:
        edits += ["--failure-deliver", failure]
    if job.no_agent is False:
        edits += ["--no-agent", "--script", STUB_NAME]
    if edits:
        out = run(["cron", "edit", job.id, *edits])
        if out.returncode != 0:
            return 1, lines + [f"could not update cron job {job.id}: {(out.stderr or out.stdout).strip()[-300:]}"]
        lines.append(f"updated cron job {job.id}: {' '.join(edits)}")
    else:
        lines.append(f"cron job {job.id} already set up ({'enabled' if job.enabled else 'paused'})")
    return 0, lines


def uninstall(cfg: Config, run: Runner | None = None) -> tuple[int, list[str]]:
    if cfg.hermes_home is None:
        return 2, ["not running under Hermes (no HERMES_HOME); nothing to remove"]
    run = run or hermes_runner(cfg)
    lines, code = [], 0
    for job in find_jobs(cfg, run):
        out = run(["cron", "remove", job.id])
        if out.returncode == 0:
            lines.append(f"removed cron job {job.id}")
        else:
            code = 1
            lines.append(f"could not remove cron job {job.id}: {(out.stderr or out.stdout).strip()[-300:]}")
    path = stub_path(cfg.hermes_home)
    if path.is_file():
        path.unlink()
        lines.append(f"removed {path}")
    lines.append(f"left the journal ({cfg.root}), state ({cfg.state_dir}) and settings in place")
    return code, lines


def _enabled_plugins(home: Path) -> list[str] | None:
    try:
        import yaml
        doc = yaml.safe_load((Path(home) / "config.yaml").read_text(encoding="utf-8")) or {}
    except Exception:
        return None
    enabled = ((doc.get("plugins") or {}).get("enabled") or []) if isinstance(doc, dict) else []
    return [str(x) for x in enabled] if isinstance(enabled, list) else None


def checks(cfg: Config, src: Path, run: Runner | None = None) -> list[tuple[str, str, str]]:
    """Doctor rows (name, status ok|warn|fail, detail) for the Hermes side."""
    if cfg.hermes_home is None:
        return []
    rows = []
    home = cfg.hermes_home
    enabled = _enabled_plugins(home)
    if enabled is not None:
        rows.append(("plugin enabled", "ok" if "journal" in enabled else "warn",
                     "journal is in plugins.enabled" if "journal" in enabled else "journal is not in plugins.enabled"))
        # ``hermes.legacy_plugins``: a predecessor that captures the same chat; both enabled = every reply captured twice
        named = cfg.hermes.get("legacy_plugins")
        named = [] if named is None else named
        if not isinstance(named, list) or not all(isinstance(p, str) for p in named):
            rows.append(("legacy plugin", "warn", "hermes.legacy_plugins must be a list of plugin names"))
            named = []
        legacy = [p for p in named if p in enabled]
        if legacy:
            rows.append(("legacy plugin", "fail", f"{', '.join(legacy)} is still enabled: replies would be captured twice"))
    path = stub_path(home)
    if not path.is_file():
        rows.append(("cron stub", "fail", f"{path} missing: run `hermes journal setup`"))
    elif path.read_text(encoding="utf-8") != stub_text(src, home):
        rows.append(("cron stub", "warn", f"{path} is out of date: run `hermes journal setup`"))
    else:
        rows.append(("cron stub", "ok", str(path)))
    try:
        jobs = find_jobs(cfg, run)
    except Exception as e:
        rows.append(("cron job", "warn", f"could not list cron jobs ({type(e).__name__})"))
        return rows
    if not jobs:
        rows.append(("cron job", "fail", "no journal tick job: run `hermes journal setup`"))
    else:
        j = jobs[0]
        state = "enabled" if j.enabled else "paused"
        last = f", last run {j.last_run_at} {j.last_status}" if j.last_run_at else ""
        rows.append(("cron job", "ok" if j.enabled else "warn", f"{j.id} {state}, {j.schedule}{last}"))
        if len(jobs) > 1:
            rows.append(("cron job", "warn", f"{len(jobs)} tick jobs: {', '.join(x.id for x in jobs)}"))
    return rows
